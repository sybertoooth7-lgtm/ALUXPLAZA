try {
  fs.mkdirSync(outDir, { recursive: true });

  for (const [filename, base64Data] of Object.entries(icons)) {
    const buffer = Buffer.from(base64Data, 'base64');
    if (buffer.length === 0) {
      throw new Error(`Decoded ${filename} to 0 bytes — base64 data looks corrupted.`);
    }
    const outPath = path.join(outDir, filename);
    fs.writeFileSync(outPath, buffer);
    console.log(`Wrote ${outPath} (${buffer.length} bytes)`);
  }

  console.log('Done — all three PWA icons written to public/');
} catch (err) {
  console.error('Failed to write PWA icons:', err.message);
  process.exit(1);
}
